#!/usr/bin/env python3
"""Generates src/port/embedded/portedby.c: the "ported by Soupa" credit drawn beside the
"powered by libultraship" logo on the boot logo screen (state_logos.c).

Same format as poweredbylus.c: 96x32 RGBA16 (5551), big-endian, opaque, pre-composited onto the
logo screen's background. The name gets the libultraship wordmark's colour gradient, sampled
from poweredbylus.c so the two match.

    python3 switch/gen_credit_logo.py [--preview out.png]
"""
import argparse
import os
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 96, 32
SS = 8  # supersampling
NAME = "Soupa"
FONT = "/usr/share/fonts/truetype/ubuntu/Ubuntu-Italic[wdth,wght].ttf"  # system font (Ubuntu)


def font(size, style):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_name(style)
    return f


def decode(c_path):
    src = open(c_path).read()
    vals = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", src[src.index("{") + 1:src.rindex("}")])]
    img = Image.new("RGB", (W, H))
    for i in range(W * H):
        v = (vals[2 * i] << 8) | vals[2 * i + 1]
        img.putpixel((i % W, i // W), tuple(((v >> s) & 31) * 255 // 31 for s in (11, 6, 1)))
    return img


def wordmark_gradient(lus):
    """Per-column colour of the libultraship wordmark (its saturated pixels), left to right."""
    cols = []
    for x in range(W):
        px = [lus.getpixel((x, y)) for y in range(12, H)]
        px = [p for p in px if max(p) - min(p) > 60]
        if px:
            cols.append(tuple(sum(c[i] for c in px) // len(px) for i in range(3)))
    return cols


def render(lus):
    bg = lus.getpixel((0, 0))
    dark = min((lus.getpixel((x, y)) for x in range(W) for y in range(0, 11)), key=sum)
    big = Image.new("L", (W * SS, H * SS), 0)
    small = Image.new("L", (W * SS, H * SS), 0)
    # "ported by", matching the small dark "powered by" line (rows ~2-10)
    f_small = font(7 * SS, "Extra Bold Italic")
    d = ImageDraw.Draw(small)
    tw = d.textlength("ported by", font=f_small)
    d.text(((W * SS - tw) / 2, 1.5 * SS), "ported by", font=f_small, fill=255)
    # the name, as large as fits the wordmark's band (rows ~12-31)
    size = 24
    while True:
        f_big = font(size * SS, "Extra Bold Italic")
        box = ImageDraw.Draw(big).textbbox((0, 0), NAME, font=f_big)
        if box[2] - box[0] <= (W - 8) * SS and box[3] - box[1] <= 18 * SS:
            break
        size -= 1
    bw, bh = box[2] - box[0], box[3] - box[1]
    ImageDraw.Draw(big).text(((W * SS - bw) / 2 - box[0], 12.5 * SS - box[1]), NAME, font=f_big, fill=255)
    big = big.resize((W, H), Image.LANCZOS)
    small = small.resize((W, H), Image.LANCZOS)

    grad = wordmark_gradient(lus)
    x0 = (W - bw / SS) / 2
    out = Image.new("RGB", (W, H), bg)
    for y in range(H):
        for x in range(W):
            t = min(max((x - x0) / max(bw / SS, 1), 0.0), 1.0)
            col = grad[min(int(t * (len(grad) - 1)), len(grad) - 1)]
            p = bg
            for a, c in ((small.getpixel((x, y)) / 255, dark), (big.getpixel((x, y)) / 255, col)):
                p = tuple(round(p[i] * (1 - a) + c[i] * a) for i in range(3))
            out.putpixel((x, y), p)
    return out


def to_rgba5551(img):
    data = []
    for y in range(H):
        for x in range(W):
            r, g, b = (round(v * 31 / 255) for v in img.getpixel((x, y)))
            v = (r << 11) | (g << 6) | (b << 1) | 1
            data += [v >> 8, v & 0xFF]
    return data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="also write a 4x PNG preview (credit beside the libultraship logo)")
    args = ap.parse_args()
    lus = decode(os.path.join(ROOT, "src/port/embedded/poweredbylus.c"))
    credit = render(lus)
    data = to_rgba5551(credit)
    lines = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 19]) for i in range(0, len(data), 19))
    with open(os.path.join(ROOT, "src/port/embedded/portedby.c"), "w") as f:
        f.write("// Generated by switch/gen_credit_logo.py; edit that, not this.\n"
                "// 96x32 RGBA16 (5551), big-endian, fully opaque, pre-composited onto the\n"
                "// logo screen background colour.\n\n"
                '#include "common.h"\n#include "embedded/portedby.h"\n\n'
                "u8 gPortedByLogo[PORTED_BY_WIDTH * PORTED_BY_HEIGHT * 2] ALIGNED8 = {\n" + lines + ",\n};\n")
    if args.preview:
        sheet = Image.new("RGB", (W * 2 + 8, H), lus.getpixel((0, 0)))
        sheet.paste(lus, (0, 0))
        sheet.paste(credit, (W + 8, 0))
        sheet.resize((sheet.width * 4, H * 4), Image.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
